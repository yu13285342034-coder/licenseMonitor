# -*- coding: utf-8 -*-
"""
Parser and persistent reader for FlexNet license manager debug logs.

The license manager log is the authoritative source for OUT/IN events.  lmstat
output is only a snapshot, so short checkouts can be missed completely between
two snapshots.  This module reads license.log incrementally and returns every
OUT/IN event in chronological order.
"""
import os
import re
import json
import time
import base64
import getpass
import shlex
import csv
import datetime

import yaml

from common import common


# Time-only FlexNet logs normally print "TIMESTAMP MM/DD/YYYY" once per day.
TIMESTAMP_LINE_PATTERN = re.compile(
    r'^\s*(?:\d{1,2}:\d{2}:\d{2}(?:\.\d+)?)?\s*'
    r'\(\s*lmgrd\s*\)\s+TIMESTAMP\s+'
    r'(\d{4}[-/]\d{1,2}[-/]\d{1,2}|\d{1,2}/\d{1,2}/\d{2,4}|\d{1,2}-\d{1,2}-\d{4})',
    re.IGNORECASE
)

# Both "09:45:11" and "11/12/2025 09:45:11" are common in vendor-daemon logs.
EVENT_LINE_PATTERN = re.compile(
    r'^\s*'
    r'(?P<timestamp>\d{4}[-/]\d{1,2}[-/]\d{1,2}[ T]\d{1,2}:\d{2}:\d{2}(?:\.\d+)?'
    r'|\d{1,2}/\d{1,2}/\d{2,4}[ T]\d{1,2}:\d{2}:\d{2}(?:\.\d+)?'
    r'|\d{1,2}:\d{2}:\d{2}(?:\.\d+)?)?'
    r'\s*\(\s*(?P<vendor>[^)]+)\s*\)\s+'
    r'(?P<event_type>OUT|IN)\s*:\s*'
    r'"(?P<feature>[^"]+)"\s+'
    r'(?P<user>\S+)@(?P<host>\S+)'
    r'(?P<rest>.*)$',
    re.IGNORECASE
)

EVENT_LINE_SPACE_HOST_PATTERN = re.compile(
    r'^\s*'
    r'(?P<timestamp>\d{4}[-/]\d{1,2}[-/]\d{1,2}[ T]\d{1,2}:\d{2}:\d{2}(?:\.\d+)?'
    r'|\d{1,2}/\d{1,2}/\d{2,4}[ T]\d{1,2}:\d{2}:\d{2}(?:\.\d+)?'
    r'|\d{1,2}:\d{2}:\d{2}(?:\.\d+)?)?'
    r'\s*\(\s*(?P<vendor>[^)]+)\s*\)\s+'
    r'(?P<event_type>OUT|IN)\s*:\s*'
    r'"(?P<feature>[^"]+)"\s+'
    r'(?P<user>\S+)\s+(?P<host>\S+)'
    r'(?P<rest>.*)$',
    re.IGNORECASE
)

COUNT_PATTERN = re.compile(
    r'(?:lic(?:ense)?(?:[_ -]*num(?:ber)?)?|pcount|count)\s*[:=]\s*(\d+)',
    re.IGNORECASE
)


class LicenseLogParser():
    """Incrementally parse FlexNet license debug logs."""

    def __init__(self, log_config_file='', db_path='', ssh_user=''):
        self.log_config_file = log_config_file
        self.ssh_user = str(ssh_user or '')
        self.db_path = db_path
        self.state_file = os.path.join(str(db_path), 'license_log_state.json') if db_path else ''
        self.log_dic = {}
        self.remote_dic = {}
        self.state_dic = {}
        self.pending_state_dic = {}
        self.read_result_dic = {}

        self.load_state()
        self.load_log_config()

    def load_state(self):
        """Load file offsets and rotation signatures saved by a previous run."""
        if self.state_file and os.path.exists(self.state_file):
            try:
                with open(self.state_file, 'r', encoding='utf-8') as state_file:
                    loaded_state = json.load(state_file)

                if isinstance(loaded_state, dict):
                    self.state_dic = loaded_state
            except Exception as error:
                common.bprint('Failed on loading license log state from "' + str(self.state_file) + '".', level='Warning')
                common.bprint(error, color='yellow', display_method=1, indent=9)
                self.state_dic = {}

    def save_state(self):
        """Persist committed offsets after events have been inserted into event db."""
        if not self.state_file:
            return

        state_dir = os.path.dirname(os.path.abspath(self.state_file))

        if state_dir and (not os.path.exists(state_dir)):
            try:
                os.makedirs(state_dir, exist_ok=True)
            except Exception as error:
                common.bprint('Failed on creating directory "' + str(state_dir) + '" for license log state.', level='Error')
                common.bprint(error, color='red', display_method=1, indent=9)
                return

        try:
            temporary_state_file = str(self.state_file) + '.tmp'

            with open(temporary_state_file, 'w', encoding='utf-8') as state_file:
                json.dump(self.state_dic, state_file, indent=2, sort_keys=True)

            os.replace(temporary_state_file, self.state_file)
        except Exception as error:
            common.bprint('Failed on saving license log state to "' + str(self.state_file) + '".', level='Warning')
            common.bprint(error, color='yellow', display_method=1, indent=9)

    def load_log_config(self):
        """
        Load license log paths.

        YAML files support both formats generated by tools/get_license_log.py
        and a friendlier nested format:

            "5280@lic_server": "/var/log/license.log"
            license_logs:
              "5280@lic_server": "/var/log/license.log"

        Any file which is not a valid YAML mapping is read as a plain text
        init file with one "ServerName:/path/to/license.log" line per server
        (used by the LOG CURVE tab).
        """
        if (not self.log_config_file) or (not os.path.exists(self.log_config_file)):
            return

        # Try YAML first, an existing YAML config keeps working with any suffix.
        log_config = None

        try:
            with open(self.log_config_file, 'r', encoding='utf-8') as log_config_file:
                config_data = yaml.safe_load(log_config_file)

            if isinstance(config_data, dict):
                log_config = config_data.get('license_logs', config_data)
        except Exception:
            log_config = None

        if not isinstance(log_config, dict):
            # Plain text init file with "ServerName:/path/to/license.log" lines.
            self.load_log_config_from_init_file()
            return

        try:
            for license_server, log_info in log_config.items():
                remote_host = ''
                remote_user = ''

                if isinstance(log_info, dict):
                    log_path = log_info.get('path', '')
                    remote_host = str(log_info.get('host', '') or '')
                    remote_user = str(log_info.get('user', '') or '')
                else:
                    log_path = log_info

                if isinstance(license_server, str) and isinstance(log_path, str) and log_path.strip():
                    license_server = license_server.strip()
                    expanded_path = os.path.expandvars(os.path.expanduser(log_path.strip()))
                    self.log_dic[license_server] = os.path.normpath(expanded_path) if os.path.isabs(expanded_path) else expanded_path
                    self.remote_dic[license_server] = {
                        'host': remote_host or self.get_host_from_server(license_server),
                        'user': remote_user or self.ssh_user,
                        'explicit_host': bool(remote_host),
                    }
        except Exception as error:
            common.bprint('Failed on loading license log config from "' + str(self.log_config_file) + '".', level='Warning')
            common.bprint(error, color='yellow', display_method=1, indent=9)
            self.log_dic = {}

    def load_log_config_from_init_file(self):
        """
        Load license log paths from a plain text init file.

        One license server per line, format:

            MasterServer:/apps/eda/license.log

        Empty lines and lines starting with "#" are ignored.  The log is read
        from the license server over SSH when it is not a local file.
        """
        try:
            with open(self.log_config_file, 'r', encoding='utf-8') as log_config_file:
                for config_line in log_config_file:
                    config_line = config_line.strip()

                    if (not config_line) or config_line.startswith('#'):
                        continue

                    if ':' not in config_line:
                        common.bprint('Invalid line in license log init file "' + str(self.log_config_file) + '": "' + str(config_line) + '" (expected format "ServerName:/path/to/license.log").', level='Warning')
                        continue

                    license_server, log_path = config_line.split(':', 1)
                    license_server = license_server.strip()
                    log_path = log_path.strip()

                    if (not license_server) or (not log_path):
                        common.bprint('Invalid line in license log init file "' + str(self.log_config_file) + '": "' + str(config_line) + '" (expected format "ServerName:/path/to/license.log").', level='Warning')
                        continue

                    # Keep the log path as-is (no normpath), a remote POSIX
                    # path must not be converted on a Windows client.
                    self.log_dic[license_server] = os.path.expandvars(os.path.expanduser(log_path))
                    self.remote_dic[license_server] = {
                        'host': self.get_host_from_server(license_server),
                        'user': self.ssh_user,
                        'explicit_host': False,
                    }
        except Exception as error:
            common.bprint('Failed on loading license log init file from "' + str(self.log_config_file) + '".', level='Warning')
            common.bprint(error, color='yellow', display_method=1, indent=9)
            self.log_dic = {}

    @staticmethod
    def get_host_from_server(license_server):
        """
        Get SSH host from a FlexNet server key such as 5280@lic_host.
        """
        license_server = str(license_server).strip()

        if '@' in license_server:
            return license_server.split('@', 1)[1]

        return license_server

    def set_log_paths(self, log_paths, override=False):
        """
        Add automatically discovered paths.  YAML paths are manual overrides and
        are therefore preserved unless override=True.
        """
        if not isinstance(log_paths, dict):
            return

        for license_server, log_path in log_paths.items():
            if (not isinstance(license_server, str)) or (not isinstance(log_path, str)) or (not log_path.strip()):
                continue

            license_server = license_server.strip()
            expanded_path = os.path.expandvars(os.path.expanduser(log_path.strip()))

            if override or (license_server not in self.log_dic):
                if os.path.isabs(expanded_path):
                    self.log_dic[license_server] = os.path.normpath(expanded_path)
                else:
                    self.log_dic[license_server] = expanded_path
                self.remote_dic[license_server] = {
                    'host': self.get_host_from_server(license_server),
                    'user': self.ssh_user,
                    'explicit_host': False,
                }

    @staticmethod
    def discover_license_log_paths(license_server_list, ssh_user='', license_files_dic=None):
        """
        Discover FlexNet manager log paths from running lmgrd processes.

        This uses the same SSH + ps logic as SERVER tab's license-log viewer.
        netstat is kept only as a fallback when ps output cannot identify which
        lmgrd process belongs to which port.  license_files_dic comes from
        lmstat and is used to disambiguate hosts running several lmgrd daemons.
        """
        if not isinstance(license_server_list, (list, tuple, set)):
            return {}

        if not isinstance(license_files_dic, dict):
            license_files_dic = {}

        user_name = str(ssh_user or getpass.getuser())
        candidates_by_host = {}

        for license_server in license_server_list:
            license_server = str(license_server).strip()

            if not license_server:
                continue

            host_name = license_server.split('@', 1)[1] if '@' in license_server else license_server
            candidates_by_host.setdefault(host_name, []).append(license_server)

        discovered_log_dic = {}
        ps_process_pattern = re.compile(r'^.*lmgrd.*\s+-c\s+(.*?)\s+-l\s+(\S+)\s*.*$', re.IGNORECASE)
        ps_pid_pattern = re.compile(r'^\S+\s+(\d+)\s+.*lmgrd\s+.*-l\s+(\S+).*$', re.IGNORECASE)

        for host_name in sorted(candidates_by_host.keys()):
            pid_port_dic = {}
            process_log_dic = {}
            process_license_dic = {}
            port_log_dic = {}
            command = 'ps -aux | grep lmgrd ; netstat -anp | grep lmgrd'
            stdout_list = common.ssh_client(host_name=host_name, user_name=user_name, command=command, timeout=1)

            for line in stdout_list:
                process_match = ps_process_pattern.match(line)
                netstat_match = re.match(r'^\s*\S+\s+\d+\s+\d+\s+\S+:(\d+)\s+.*\b(ESTABLISHED|LISTEN)\s+(\d+)/lmgrd\s*$', line, re.IGNORECASE)
                pid_match = ps_pid_pattern.match(line)

                if process_match:
                    process_license_dic_key = str(process_match.group(1)).strip()
                    process_log_path = str(process_match.group(2)).strip()
                    process_id = ''
                    pid_match_for_process = ps_pid_pattern.match(line)

                    if pid_match_for_process:
                        process_id = pid_match_for_process.group(1)

                    if process_id:
                        process_log_dic[process_id] = process_log_path
                        process_license_dic[process_id] = process_license_dic_key
                elif netstat_match:
                    pid_port_dic[netstat_match.group(3)] = netstat_match.group(1)

            for process_id, port in pid_port_dic.items():
                if process_id in process_log_dic:
                    port_log_dic[str(port)] = process_log_dic[process_id]

            ps_candidates = list(process_log_dic.values())
            netstat_candidates = list(port_log_dic.values())
            candidates = candidates_by_host[host_name]

            # Preferred behavior: exactly what View License Log does on the
            # SERVER/FEATURE/USAGE tabs -- match the lmstat license file list
            # against "-c" on the running lmgrd command line.
            for license_server in candidates:
                expected_license_files = str(license_files_dic.get(license_server, '')).strip()

                # lmstat uses the hostname shown by "License server status",
                # while sampling/database keys normally use port@hostname.
                if (not expected_license_files) and ('@' in license_server):
                    expected_license_files = str(license_files_dic.get(license_server.split('@', 1)[1], '')).strip()

                if not expected_license_files:
                    for metadata_server, metadata_license_files in license_files_dic.items():
                        metadata_host = metadata_server.split('@', 1)[1] if '@' in metadata_server else metadata_server

                        if metadata_host == host_name:
                            expected_license_files = str(metadata_license_files).strip()
                            break

                matched_logs = []

                for process_id, process_license_files in process_license_dic.items():
                    if expected_license_files and (expected_license_files.find(process_license_files) != -1):
                        matched_logs.append(process_log_dic[process_id])

                matched_logs = list(dict.fromkeys(matched_logs))

                if len(matched_logs) == 1:
                    discovered_log_dic[license_server] = matched_logs[0]

            # If lmstat could not provide a license-file list, allow a single
            # lmgrd process on the host.  With several daemons, remain silent
            # instead of attaching the wrong log.
            if len(candidates) == 1 and (candidates[0] not in discovered_log_dic) and (len(ps_candidates) == 1):
                discovered_log_dic[candidates[0]] = ps_candidates[0]

            # Last fallback: old port-based relationship when ps/license-file
            # matching is ambiguous.
            for port, log_path in port_log_dic.items():
                preferred_server = str(port) + '@' + str(host_name)

                if preferred_server in candidates and (preferred_server not in discovered_log_dic):
                    discovered_log_dic[preferred_server] = log_path
                elif len(candidates) == 1 and (candidates[0] not in discovered_log_dic):
                    discovered_log_dic[candidates[0]] = log_path

        return discovered_log_dic

    @staticmethod
    def shell_quote(value):
        """
        Quote a path safely for the remote POSIX shell.
        """
        return shlex.quote(str(value))

    @staticmethod
    def get_file_signature(log_path):
        """Return a base64 signature used to detect log replacement/rotation."""
        try:
            with open(log_path, 'rb') as log_file:
                return base64.b64encode(log_file.read(4096)).decode('ascii')
        except Exception:
            return ''

    def get_remote_log_chunk(self, license_server, log_path, offset):
        """
        Read size/head-signature/new bytes from a remote license.log via SSH.

        base64 keeps the transfer byte-safe.  tail -c +N uses one-based byte
        numbering, therefore an offset of zero becomes +1.
        """
        remote_info = self.remote_dic.get(license_server, {})
        host_name = str(remote_info.get('host') or self.get_host_from_server(license_server))
        user_name = str(remote_info.get('user') or self.ssh_user or getpass.getuser())
        quoted_path = self.shell_quote(log_path)
        marker = '__LICENSE_MONITOR_LOG_DATA__'
        command = (
            'printf "%s\\n" "$(wc -c < ' + quoted_path + ')"; '
            'head -c 4096 ' + quoted_path + ' | base64; '
            'printf "\\n' + marker + '\\n"; '
            'tail -c +' + str(int(offset) + 1) + ' ' + quoted_path + ' | base64'
        )
        stdout_list = common.ssh_client(host_name=host_name, user_name=user_name, command=command, timeout=1)

        if not stdout_list:
            # common.ssh_client returns an empty list when login fails or the
            # remote channel produces no stdout.  Run a tiny probe so the
            # concise LOG READ line can distinguish auth/host issues from an
            # ordinary command failure.
            probe_command = 'printf "%s\\n" __LICENSE_MONITOR_SSH_PROBE_OK__; id -un; hostname'
            probe_result = common.ssh_client(host_name=host_name, user_name=user_name, command=probe_command, timeout=1)
            probe_text = '\n'.join(probe_result)

            if '__LICENSE_MONITOR_SSH_PROBE_OK__' not in probe_text:
                raise IOError('ssh-login-failed')

            raise IOError('ssh-command-empty-result')

        marker_index = None

        for index in range(1, len(stdout_list)):
            if stdout_list[index].strip() == marker:
                marker_index = index
                break

        if marker_index is None:
            raise IOError('invalid result from SSH command')

        current_size = int(stdout_list[0].strip())
        signature_b64 = ''.join(stdout_list[1:marker_index]).strip()
        data_b64 = ''.join(stdout_list[(marker_index + 1):]).strip()
        signature_bytes = base64.b64decode(signature_b64) if signature_b64 else b''
        new_bytes = base64.b64decode(data_b64) if data_b64 else b''

        return current_size, base64.b64encode(signature_bytes).decode('ascii'), new_bytes

    def get_log_events(self, license_server):
        """
        Read only new complete lines for one server.

        If the discovered path is not local, read it on the license server over
        SSH.  Returned events are held in pending_state_dic until
        commit_log_state() is called, so a SQLite failure cannot lose events.
        """
        event_list = []

        if license_server not in self.log_dic:
            return event_list

        log_path = self.log_dic[license_server]
        remote_info = self.remote_dic.get(license_server, {})
        force_remote = bool(remote_info.get('explicit_host', False))
        local_file_exists = os.path.exists(log_path)
        self.read_result_dic[license_server] = {
            'status': 'NOT_READ',
            'path': log_path,
            'new_events': 0,
            'reason': '',
        }

        if (not local_file_exists) and (not remote_info.get('host')):
            self.read_result_dic[license_server]['status'] = 'ERROR'
            self.read_result_dic[license_server]['reason'] = 'file-not-found'
            common.bprint('License log file "' + str(log_path) + '" does not exist for server "' + str(license_server) + '".', level='Warning')
            return event_list

        try:
            if force_remote or (not local_file_exists):
                saved_state = self.state_dic.get(log_path, {})
                last_offset = int(saved_state.get('offset', 0))
                saved_signature = str(saved_state.get('signature', ''))
                current_size, current_signature, new_bytes = self.get_remote_log_chunk(license_server, log_path, last_offset)

                if current_size < last_offset or (saved_signature and (current_signature != saved_signature)):
                    last_offset = 0
                    current_size, current_signature, new_bytes = self.get_remote_log_chunk(license_server, log_path, last_offset)
            else:
                current_size = os.path.getsize(log_path)
                current_signature = self.get_file_signature(log_path)
                saved_state = self.state_dic.get(log_path, {})
                last_offset = int(saved_state.get('offset', 0))
                saved_signature = str(saved_state.get('signature', ''))

                if current_size < last_offset or (saved_signature and (current_signature != saved_signature)):
                    last_offset = 0

                with open(log_path, 'rb') as log_file:
                    log_file.seek(last_offset)
                    new_bytes = log_file.read()

            # Never consume an incomplete final line.  It will be completed and
            # picked up by the next sampling run.
            self.read_result_dic[license_server]['status'] = 'READ'
            complete_length = new_bytes.rfind(b'\n') + 1
            if complete_length <= 0:
                return event_list

            new_content = new_bytes[:complete_length].decode('utf-8', errors='ignore')
            event_list = self.parse_log_content(new_content)
            new_offset = last_offset + complete_length

            self.read_result_dic[license_server]['new_events'] = len(event_list)

            for event in event_list:
                event['license_server'] = license_server

            self.pending_state_dic[log_path] = {
                'offset': new_offset,
                'size': current_size,
                'signature': current_signature,
                'updated_second': int(time.time()),
            }
        except Exception as error:
            self.read_result_dic[license_server]['status'] = 'ERROR'
            self.read_result_dic[license_server]['reason'] = str(error).replace('\n', ' ')[:200]
            common.bprint('Failed on reading license log "' + str(log_path) + '".', level='Warning')
            common.bprint(error, color='yellow', display_method=1, indent=9)
            return []

        return event_list

    def commit_log_state(self):
        """Commit offsets for all logs successfully read in this run."""
        if not self.pending_state_dic:
            return

        for log_path, state in self.pending_state_dic.items():
            self.state_dic[log_path] = state

        self.save_state()
        self.pending_state_dic = {}

    @staticmethod
    def parse_date_string(date_string):
        """Parse FlexNet date strings; ambiguous slash dates use MM/DD/YYYY."""
        date_formats = ('%m/%d/%Y', '%m/%d/%y', '%Y-%m-%d', '%Y/%m/%d', '%m-%d-%Y')

        for date_format in date_formats:
            try:
                return datetime.datetime.strptime(date_string, date_format).date()
            except ValueError:
                continue

        return None

    @classmethod
    def parse_exact_timestamp(cls, timestamp_string):
        """Convert a timestamp containing a date into a datetime object."""
        timestamp_formats = (
            '%Y-%m-%d %H:%M:%S.%f',
            '%Y-%m-%d %H:%M:%S',
            '%Y-%m-%dT%H:%M:%S.%f',
            '%Y-%m-%dT%H:%M:%S',
            '%m/%d/%Y %H:%M:%S.%f',
            '%m/%d/%Y %H:%M:%S',
            '%m/%d/%y %H:%M:%S.%f',
            '%m/%d/%y %H:%M:%S',
        )

        for timestamp_format in timestamp_formats:
            try:
                return datetime.datetime.strptime(timestamp_string, timestamp_format)
            except ValueError:
                continue

        date_part = timestamp_string.split()[0]
        time_part = timestamp_string.split()[1]
        parsed_date = cls.parse_date_string(date_part)

        if parsed_date:
            try:
                parsed_time = datetime.datetime.strptime(time_part, '%H:%M:%S.%f').time()
                return datetime.datetime.combine(parsed_date, parsed_time)
            except ValueError:
                pass

        return None

    @classmethod
    def parse_log_content(cls, content, reference_now=None):
        """
        Parse a complete chunk and infer dates for time-only FlexNet lines.

        FlexNet logs commonly contain only HH:MM:SS.  A daily TIMESTAMP line and
        backwards time jumps are used to reconstruct the correct day, instead of
        incorrectly mapping every historical event to today.
        """
        now = reference_now or datetime.datetime.now()
        current_date = now.date()
        saw_time = False
        last_time_of_day = None
        event_list = []
        unmatched_event_lines = []

        for raw_line in content.splitlines():
            line = raw_line.strip()

            timestamp_match = TIMESTAMP_LINE_PATTERN.match(line)
            if timestamp_match:
                parsed_date = cls.parse_date_string(timestamp_match.group(1))

                if parsed_date:
                    current_date = parsed_date
                    saw_time = True
                    last_time_of_day = None
                continue

            match = EVENT_LINE_PATTERN.match(line)

            if not match:
                match = EVENT_LINE_SPACE_HOST_PATTERN.match(line)

            if not match:
                if re.search(r'\b(?:OUT|IN)\s*:', line, re.IGNORECASE) and (len(unmatched_event_lines) < 10):
                    unmatched_event_lines.append(line)
                continue

            timestamp_string = match.group('timestamp') or ''
            exact_datetime = cls.parse_exact_timestamp(timestamp_string) if timestamp_string and (' ' in timestamp_string or 'T' in timestamp_string) else None

            if exact_datetime:
                current_date = exact_datetime.date()
                event_datetime = exact_datetime
                last_time_of_day = event_datetime.time()
            else:
                try:
                    parsed_time = datetime.datetime.strptime(timestamp_string, '%H:%M:%S.%f')
                except ValueError:
                    try:
                        parsed_time = datetime.datetime.strptime(timestamp_string, '%H:%M:%S')
                    except ValueError:
                        continue

                parsed_time = parsed_time.time()

                # Time-only FlexNet logs omit the date.  A backward time value
                # means the log crossed midnight.
                if (last_time_of_day is not None) and (parsed_time < last_time_of_day):
                    current_date = current_date + datetime.timedelta(days=1)

                candidate = datetime.datetime.combine(current_date, parsed_time)

                if not saw_time and (candidate > now + datetime.timedelta(minutes=5)):
                    current_date = current_date - datetime.timedelta(days=1)
                    candidate = datetime.datetime.combine(current_date, parsed_time)

                event_datetime = candidate
                last_time_of_day = parsed_time
                saw_time = True

            lic_num = cls.parse_license_count(match.group('rest'))
            event_list.append({
                'timestamp_second': int(time.mktime(event_datetime.timetuple())),
                'timestamp_str': timestamp_string,
                'event_type': match.group('event_type').upper(),
                'vendor': match.group('vendor').strip(),
                'feature': match.group('feature').strip(),
                'user': match.group('user').strip(),
                'host': match.group('host').strip(' .,;'),
                'lic_num': lic_num,
                'raw_line': line,
            })

        if unmatched_event_lines:
            common.bprint('Some OUT/IN lines did not match the supported FlexNet format:', level='Warning')

            for line in unmatched_event_lines:
                common.bprint(line, color='yellow', display_method=1, indent=9)

        return event_list

    @staticmethod
    def parse_license_count(rest_string):
        """
        Extract checkout/checkin count.

        Formats handled include "(LICENSE pcount: 3)", "(Lic_num: 2)",
        and "licenses=2".  FlexNet logs without an explicit count consume one
        license; unrelated numeric handles are not treated as counts.
        """
        if rest_string:
            count_match = COUNT_PATTERN.search(rest_string)

            if count_match:
                return str(max(1, int(count_match.group(1))))

            return '1'

        return '1'

    @staticmethod
    def convert_log_timestamp(timestamp_string, reference_now=None):
        """Compatibility helper used by reporting tools."""
        parser = LicenseLogParser()
        exact_datetime = parser.parse_exact_timestamp(timestamp_string)

        if exact_datetime:
            return int(time.mktime(exact_datetime.timetuple()))

        now = reference_now or datetime.datetime.now()

        try:
            parsed_time = datetime.datetime.strptime(timestamp_string, '%H:%M:%S')
            full_datetime = now.replace(hour=parsed_time.hour, minute=parsed_time.minute, second=parsed_time.second, microsecond=0)
        except ValueError:
            return None

        if full_datetime > now + datetime.timedelta(minutes=5):
            full_datetime = full_datetime - datetime.timedelta(days=1)

        return int(time.mktime(full_datetime.timetuple()))

    # ----------------------------------------------------------------------
    # Shared LOG CURVE data helpers.
    #
    # A collector host (cron "license_sample") reads license.log over SSH and
    # stores events into db_path/license_log/<log name>/events.csv (one
    # directory per log file, plus a log_info.txt marker).  The GUI host reads
    # these csv files directly, so it never needs SSH access to license
    # servers.
    # ----------------------------------------------------------------------

    # events.csv columns.  Older files only contain the first 8 columns and
    # are still accepted by load_events_csv().
    EVENT_CSV_TITLE_LIST = ['timestamp_second', 'timestamp_str', 'event_type', 'vendor', 'feature', 'user', 'host', 'lic_num', 'license_server', 'log_path']

    @staticmethod
    def get_event_signature(event):
        """
        Get a unique signature for one license log event (used for csv dedup).
        """
        try:
            lic_num = int(event.get('lic_num', 1))
        except (TypeError, ValueError):
            lic_num = 1

        try:
            timestamp_second = int(event.get('timestamp_second', 0))
        except (TypeError, ValueError):
            timestamp_second = 0

        return (timestamp_second, str(event.get('event_type', '')).upper(), str(event.get('feature', '')), str(event.get('user', '')), str(event.get('host', '')), lic_num)

    @classmethod
    def merge_event_lists(cls, stored_event_list=[], new_event_list=[]):
        """
        Merge new events into stored events, skip events which are already
        stored (protects against duplicated reads after crash or rotation).
        """
        signature_set = set()

        for event in stored_event_list:
            signature_set.add(cls.get_event_signature(event))

        merged_event_list = list(stored_event_list)

        for event in new_event_list:
            signature = cls.get_event_signature(event)

            if signature not in signature_set:
                signature_set.add(signature)
                merged_event_list.append(event)

        return merged_event_list

    def get_log_store_dir_name(self, license_server, log_path):
        """
        Get the store directory name for one license log.

        The directory is named after the log file name (for example
        "license.log").  When several entries use logs with the same file
        name, the server name (and a counter if necessary) is appended to
        keep directory names unique.
        """
        if not hasattr(self, '_log_store_name_dic'):
            self._log_store_name_dic = {}

        log_path = str(log_path)
        base_name = os.path.basename(log_path.rstrip('/\\').strip()) or 'license.log'
        base_store_name = re.sub(r'[^A-Za-z0-9._-]', '_', base_name) or 'license.log'
        used_paths = self._log_store_name_dic.setdefault(base_store_name, [])

        if log_path in used_paths:
            return base_store_name

        if not used_paths:
            used_paths.append(log_path)
            return base_store_name

        server_suffix = re.sub(r'[^A-Za-z0-9._-]', '_', str(license_server)) or 'server'
        candidate = base_store_name + '__' + server_suffix
        index = 2

        while candidate in self._log_store_name_dic and (log_path not in self._log_store_name_dic[candidate]):
            candidate = base_store_name + '__' + server_suffix + '__' + str(index)
            index += 1

        self._log_store_name_dic.setdefault(candidate, []).append(log_path)

        return candidate

    @classmethod
    def load_events_csv(cls, events_csv_file):
        """
        Load stored license log events from csv file.

        Both the old 8-column format (GUI only) and the new 10-column format
        (with license_server/log_path) are accepted.
        """
        event_list = []

        if (not events_csv_file) or (not os.path.exists(events_csv_file)):
            return event_list

        try:
            with open(events_csv_file, 'r', encoding='utf-8', newline='') as events_csv:
                csv_reader = csv.DictReader(events_csv)

                for row in csv_reader:
                    try:
                        timestamp_second = int(row.get('timestamp_second', 0))
                    except (TypeError, ValueError):
                        continue

                    try:
                        lic_num = str(int(row.get('lic_num', '1')))
                    except (TypeError, ValueError):
                        lic_num = '1'

                    event_list.append({
                                       'timestamp_second': timestamp_second,
                                       'timestamp_str': str(row.get('timestamp_str', '')),
                                       'event_type': str(row.get('event_type', '')).upper(),
                                       'vendor': str(row.get('vendor', '')),
                                       'feature': str(row.get('feature', '')),
                                       'user': str(row.get('user', '')),
                                       'host': str(row.get('host', '')),
                                       'lic_num': lic_num,
                                       'license_server': str(row.get('license_server', '')),
                                       'log_path': str(row.get('log_path', '')),
                                      })
        except Exception as error:
            common.bprint('Failed on loading license log events csv "' + str(events_csv_file) + '".', level='Warning')
            common.bprint(error, color='yellow', display_method=1, indent=9)

        return event_list

    @classmethod
    def write_events_csv(cls, events_csv_file, event_list=[]):
        """
        Write license log events into csv file (10 columns).
        """
        events_dir = os.path.dirname(os.path.abspath(events_csv_file))

        if events_dir and (not os.path.exists(events_dir)):
            os.makedirs(events_dir, mode=0o755, exist_ok=True)

        with open(events_csv_file, 'w', encoding='utf-8', newline='') as events_csv:
            csv_writer = csv.writer(events_csv)
            csv_writer.writerow(cls.EVENT_CSV_TITLE_LIST)

            for event in event_list:
                csv_writer.writerow([event['timestamp_second'], event['timestamp_str'], event['event_type'], event['vendor'], event['feature'], event['user'], event['host'], event['lic_num'], event.get('license_server', ''), event.get('log_path', '')])

    def parse_log_line(self, line):
        """Parse one line when its date is already known or embeds a date."""
        events = self.parse_log_content(line)

        return events[0] if events else None
